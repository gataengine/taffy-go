// Package grid provides functions for initializing grid tracks from styles.
// This file is a port of compute/grid/explicit_grid.rs from the Taffy Rust layout engine.
package grid

import (
	"github.com/gataengine/taffy-go/lib"
	"math"

	"github.com/gataengine/taffy-go/geometry"
	"github.com/gataengine/taffy-go/style"
)

// autoRepeatStrategy controls how auto-repeat tracks are sized.
type autoRepeatStrategy int

const (
	// autoRepeatMaxRepsNoOverflow sizes auto-repeat tracks to the largest count that doesn't overflow.
	autoRepeatMaxRepsNoOverflow autoRepeatStrategy = iota
	// autoRepeatMinRepsOverflow sizes auto-repeat tracks to the smallest count that overflows.
	autoRepeatMinRepsOverflow
)

// computeExplicitGridSizeInAxis computes the number of rows/columns in the explicit grid for an axis.
// Returns (numAutoRepetitions, gridTemplateTrackCount).
func computeExplicitGridSizeInAxis(
	containerStyle style.GridContainerStyle,
	autoFitContainerSize lib.Option[float32],
	strategy autoRepeatStrategy,
	resolveCalcValue style.CalcResolver,
	axis geometry.AbsoluteAxis,
) (uint16, uint16) {
	var template []style.GridTemplateComponent
	switch axis {
	case geometry.AbsoluteAxisHorizontal:
		template = containerStyle.GetGridTemplateColumns()
	case geometry.AbsoluteAxisVertical:
		template = containerStyle.GetGridTemplateRows()
	}

	if template == nil {
		return 0, 0
	}

	trackCount := len(template)
	if trackCount == 0 {
		return 0, 0
	}

	// If there are any repetitions that contain no tracks, the whole definition is invalid
	for _, trackDef := range template {
		if trackDef.Tag == style.GridTemplateRepeat && trackDef.Repetition.TrackCount() == 0 {
			return 0, 0
		}
	}

	// Compute the number of tracks generated by single definitions and fixed-count repetitions
	var nonAutoRepeatingTrackCount uint16
	for _, trackDef := range template {
		switch trackDef.Tag {
		case style.GridTemplateSingle:
			nonAutoRepeatingTrackCount++
		case style.GridTemplateRepeat:
			rep := trackDef.Repetition
			switch rep.Count.Tag {
			case style.RepetitionCountFixed:
				nonAutoRepeatingTrackCount += rep.Count.Count * rep.TrackCount()
			case style.RepetitionAutoFill, style.RepetitionAutoFit:
				// Don't count auto-repeat tracks here
			}
		}
	}

	var autoRepetitionCount uint16
	for _, trackDef := range template {
		if trackDef.IsAutoRepetition() {
			autoRepetitionCount++
		}
	}

	allTrackDefsHaveFixedComponent := true
	for _, trackDef := range template {
		switch trackDef.Tag {
		case style.GridTemplateSingle:
			if !style.TrackHasFixedComponent(trackDef.Single) {
				allTrackDefsHaveFixedComponent = false
			}
		case style.GridTemplateRepeat:
			for _, sf := range trackDef.Repetition.Tracks {
				if !style.TrackHasFixedComponent(sf) {
					allTrackDefsHaveFixedComponent = false
					break
				}
			}
		}
		if !allTrackDefsHaveFixedComponent {
			break
		}
	}

	templateIsValid := autoRepetitionCount == 0 || (autoRepetitionCount == 1 && allTrackDefsHaveFixedComponent)
	if !templateIsValid {
		return 0, 0
	}

	if autoRepetitionCount == 0 {
		return 0, nonAutoRepeatingTrackCount
	}

	// Find the auto-repeat definition
	var repetitionDef style.GridTemplateRepetition
	for _, def := range template {
		if def.Tag == style.GridTemplateRepeat {
			switch def.Repetition.Count.Tag {
			case style.RepetitionAutoFill, style.RepetitionAutoFit:
				repetitionDef = def.Repetition
			}
		}
	}
	repetitionTrackCount := repetitionDef.TrackCount()

	// Determine the number of repetitions
	var numRepetitions uint16
	if !autoFitContainerSize.IsSome {
		numRepetitions = 1
	} else {
		innerContainerSize := autoFitContainerSize.Value
		parentSize := lib.Some(innerContainerSize)

		trackDefiniteValue := func(sf style.TrackSizingFunction) float32 {
			maxSize := style.TrackMaxSizingFunction_(sf).DefiniteValue(parentSize, resolveCalcValue)
			minSize := style.TrackMinSizingFunction_(sf).DefiniteValue(parentSize, resolveCalcValue)
			if maxSize.IsSome {
				val := maxSize.Value
				if minSize.IsSome && minSize.Value > val {
					val = minSize.Value
				}
				return val
			}
			if minSize.IsSome {
				return minSize.Value
			}
			return 0
		}

		var nonRepeatingTrackUsedSpace float32
		for _, trackDef := range template {
			switch trackDef.Tag {
			case style.GridTemplateSingle:
				nonRepeatingTrackUsedSpace += trackDefiniteValue(trackDef.Single)
			case style.GridTemplateRepeat:
				rep := trackDef.Repetition
				switch rep.Count.Tag {
				case style.RepetitionCountFixed:
					var sum float32
					for _, sf := range rep.Tracks {
						sum += trackDefiniteValue(sf)
					}
					nonRepeatingTrackUsedSpace += sum * float32(rep.Count.Count)
				case style.RepetitionAutoFill, style.RepetitionAutoFit:
					// skip
				}
			}
		}

		gapSize := style.ResolveOrZeroLP(
			containerStyle.GetGap().GetAbs(axis),
			lib.Some(innerContainerSize),
			resolveCalcValue,
		)

		// Compute the amount of space that a single repetition of the repeated track list takes
		var perRepetitionTrackUsedSpace float32
		for _, sf := range repetitionDef.Tracks {
			perRepetitionTrackUsedSpace += trackDefiniteValue(sf)
		}

		// Special case the first repetition
		satSub := nonAutoRepeatingTrackCount + repetitionTrackCount
		if satSub > 0 {
			satSub--
		}
		firstRepetitionAndNonRepeatingTracksUsedSpace := nonRepeatingTrackUsedSpace +
			perRepetitionTrackUsedSpace +
			float32(satSub)*gapSize

		if firstRepetitionAndNonRepeatingTracksUsedSpace > innerContainerSize {
			numRepetitions = 1
		} else {
			perRepetitionGapUsedSpace := float32(repetitionTrackCount) * gapSize
			perRepetitionUsedSpace := perRepetitionTrackUsedSpace + perRepetitionGapUsedSpace
			numRepetitionThatFit := (innerContainerSize - firstRepetitionAndNonRepeatingTracksUsedSpace) / perRepetitionUsedSpace

			switch strategy {
			case autoRepeatMaxRepsNoOverflow:
				numRepetitions = uint16(math.Floor(float64(numRepetitionThatFit))) + 1
			case autoRepeatMinRepsOverflow:
				numRepetitions = uint16(math.Ceil(float64(numRepetitionThatFit))) + 1
			}
		}
	}

	gridTemplateTrackCount := nonAutoRepeatingTrackCount + (repetitionTrackCount * numRepetitions)
	return numRepetitions, gridTemplateTrackCount
}

// initializeGridTracks creates the full track list including implicit tracks, explicit tracks, and gutters.
func initializeGridTracks(
	tracks *[]gridTrack,
	counts TrackCounts,
	containerStyle style.GridContainerStyle,
	axis geometry.AbsoluteAxis,
	trackHasItems func(int) bool,
) {
	var trackTemplate []style.GridTemplateComponent
	var autoTracks []style.TrackSizingFunction
	var gap style.LengthPercentage
	switch axis {
	case geometry.AbsoluteAxisHorizontal:
		trackTemplate = containerStyle.GetGridTemplateColumns()
		autoTracks = containerStyle.GetGridAutoColumns()
		gap = containerStyle.GetGap().Width
	case geometry.AbsoluteAxisVertical:
		trackTemplate = containerStyle.GetGridTemplateRows()
		autoTracks = containerStyle.GetGridAutoRows()
		gap = containerStyle.GetGap().Height
	}

	// Clear and reserve space
	*tracks = (*tracks)[:0]
	totalCap := counts.Len()*2 + 1
	if cap(*tracks) < totalCap {
		*tracks = make([]gridTrack, 0, totalCap)
	}
	*tracks = append(*tracks, gridTrackGutter(gap))

	autoTrackCount := len(autoTracks)

	// Create negative implicit tracks
	if counts.NegativeImplicit > 0 {
		if autoTrackCount == 0 {
			createImplicitTracksAuto(tracks, counts.NegativeImplicit, gap)
		} else {
			offset := autoTrackCount - (int(counts.NegativeImplicit) % autoTrackCount)
			createImplicitTracksWithOffset(tracks, counts.NegativeImplicit, autoTracks, offset, gap)
		}
	}

	currentTrackIndex := int(counts.NegativeImplicit)

	// Create explicit tracks
	if counts.Explicit > 0 && trackTemplate != nil {
		for _, trackDef := range trackTemplate {
			switch trackDef.Tag {
			case style.GridTemplateSingle:
				sf := trackDef.Single
				*tracks = append(*tracks, newGridTrack(style.TrackMinSizingFunction_(sf), style.TrackMaxSizingFunction_(sf)))
				*tracks = append(*tracks, gridTrackGutter(gap))
				currentTrackIndex++
			case style.GridTemplateRepeat:
				rep := trackDef.Repetition
				switch rep.Count.Tag {
				case style.RepetitionCountFixed:
					total := int(rep.TrackCount()) * int(rep.Count.Count)
					for i := 0; i < total; i++ {
						sf := rep.Tracks[i%len(rep.Tracks)]
						*tracks = append(*tracks, newGridTrack(style.TrackMinSizingFunction_(sf), style.TrackMaxSizingFunction_(sf)))
						*tracks = append(*tracks, gridTrackGutter(gap))
						currentTrackIndex++
					}
				case style.RepetitionAutoFill, style.RepetitionAutoFit:
					autoRepeatedTrackCount := int(counts.Explicit) - (len(trackTemplate) - 1)
					for i := 0; i < autoRepeatedTrackCount; i++ {
						sf := rep.Tracks[i%len(rep.Tracks)]
						track := newGridTrack(style.TrackMinSizingFunction_(sf), style.TrackMaxSizingFunction_(sf))
						gutter := gridTrackGutter(gap)

						// Auto-fit tracks that don't contain items should be collapsed
						if rep.Count.Tag == style.RepetitionAutoFit && !trackHasItems(currentTrackIndex) {
							track.collapse()
							gutter.collapse()
						}

						*tracks = append(*tracks, track)
						*tracks = append(*tracks, gutter)
						currentTrackIndex++
					}
				}
			}
		}
	}

	gridAreaTracks := int(counts.NegativeImplicit+counts.Explicit) - currentTrackIndex

	// Create positive implicit tracks
	positiveCount := counts.PositiveImplicit + uint16(gridAreaTracks)
	if autoTrackCount == 0 {
		createImplicitTracksAuto(tracks, positiveCount, gap)
	} else {
		createImplicitTracksWithOffset(tracks, positiveCount, autoTracks, 0, gap)
	}

	// Mark first and last grid lines as collapsed
	(*tracks)[0].collapse()
	(*tracks)[len(*tracks)-1].collapse()
}

// createImplicitTracksAuto creates implicit tracks using AUTO sizing.
func createImplicitTracksAuto(tracks *[]gridTrack, count uint16, gap style.LengthPercentage) {
	for i := uint16(0); i < count; i++ {
		*tracks = append(*tracks, newGridTrack(style.MinTrackAutoVal, style.MaxTrackAutoVal))
		*tracks = append(*tracks, gridTrackGutter(gap))
	}
}

// createImplicitTracksWithOffset creates implicit tracks cycling through autoTracks with an offset.
func createImplicitTracksWithOffset(tracks *[]gridTrack, count uint16, autoTracks []style.TrackSizingFunction, offset int, gap style.LengthPercentage) {
	n := len(autoTracks)
	for i := uint16(0); i < count; i++ {
		idx := (int(i) + offset) % n
		sf := autoTracks[idx]
		*tracks = append(*tracks, newGridTrack(style.TrackMinSizingFunction_(sf), style.TrackMaxSizingFunction_(sf)))
		*tracks = append(*tracks, gridTrackGutter(gap))
	}
}
